# 리뷰를 가장 많이 작성한 회원의 리뷰들을 조회하기
# 1. 리뷰를 가장 많이 작성한 회원의 ID 찾기
# 2. JOIN 후에, 해당 댓글 비교


WITH REVIEW_COUNTS AS (
    SELECT MEMBER_ID, COUNT(REVIEW_ID) AS REVIEW_COUNT
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
),
MAX_REVIEWERS AS (
    SELECT MEMBER_ID
    FROM REVIEW_COUNTS R1
    WHERE REVIEW_COUNT = (
        SELECT MAX(R2.REVIEW_COUNT)
        FROM REVIEW_COUNTS R2
    )
),
MAX_REVIEWER_INFO AS (
    SELECT P.MEMBER_NAME, R.REVIEW_TEXT, R.REVIEW_DATE
    FROM REST_REVIEW R
    JOIN MEMBER_PROFILE P
    ON R.MEMBER_ID = P.MEMBER_ID
    WHERE P.MEMBER_ID IN (SELECT MEMBER_ID FROM MAX_REVIEWERS)
)
SELECT *
FROM MAX_REVIEWER_INFO
ORDER BY REVIEW_DATE ASC, REVIEW_TEXT ASC;