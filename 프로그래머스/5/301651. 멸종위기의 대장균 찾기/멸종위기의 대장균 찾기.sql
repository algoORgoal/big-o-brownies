# 1. 개체들의 세대 구하기
# 2. 자식의 개수 구하기
# 3. 자식이 0인 개체의 수 세대별로 구하기

WITH RECURSIVE GENERATIONS AS (
    SELECT *, 1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT E.*, G.GENERATION + 1
    FROM ECOLI_DATA AS E
    JOIN GENERATIONS AS G
    ON E.PARENT_ID = G.ID
), CHILD_COUNTS AS (
    SELECT G1.*, G2.ID AS CHILD_ID
    FROM GENERATIONS G1
    LEFT OUTER JOIN GENERATIONS G2
    ON G1.ID = G2.PARENT_ID
)
SELECT *
FROM CHILD_COUNTS
WHERE CHILD_ID IS NULL
